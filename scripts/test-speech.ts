let fail = 0;
const check = (name: string, got: string, want: string) => {
  if (got === want) return;
  fail++;
  console.log(`✗ ${name}\n  ได้   ${got}\n  ควรได้ ${want}`);
};
for (const [input, want] of cases) check(input, flat(speechOf(input)), want);

// จุดพัก (· / ขึ้นบรรทัด) = แบ่งท่อนเสียง
check('จุดพักแบ่งท่อน', JSON.stringify(sentencesOf(speechOf('รักษาปวดหลังไปแล้ว 3/6 ครั้งค่ะ · pain score ก่อนเริ่มรักษา 7/10 ล่าสุด 3/10 ปวดน้อยลง 57%'))), JSON.stringify(['รักษาปวดหลังไปแล้ว 3 จาก 6 ครั้งค่ะ', 'pain score ก่อนเริ่มรักษา 7 จาก 10 ล่าสุด 3 จาก 10 ปวดน้อยลง 57 เปอร์เซ็นต์']));

// ชื่อ: ตัด "คุณ…" / ชื่อเต็ม · ชื่อสั้นไม่กินคำอื่น
check('ตัดชื่อ', flat(spokenOf(['สวัสดีค่ะ คุณสมชาย วันนี้เป็นยังไงบ้างคะ'], 'สมชาย ใจดี')), 'สวัสดีค่ะ วันนี้เป็นยังไงบ้างคะ');
check('ชื่อสั้นไม่กินคำ', flat(spokenOf(['ดีขึ้นแล้วค่ะ คุณดี'], 'ดี')), 'ดีขึ้นแล้วค่ะ');

// ยาวเกิน → คำถามท้าย (keepFrom) อ่านครบ ย่อส่วนต้นแทน
const longHead = 'ประคบสมุนไพรช่วยให้กล้ามเนื้อคลายตัวค่ะ '.repeat(12);
const q = 'กลับมาที่คำถามค่ะ เป็นมานานแค่ไหนแล้วคะ?';
const out = spokenOf([longHead, q], '', 300, 1);
check('คำถามท้ายไม่ถูกตัด', String(out.endsWith('เป็นมานานแค่ไหนแล้วคะ?')), 'true');
check('ยาวไม่เกินกำหนด', String(out.length <= 300), 'true');

check('% ปวดน้อยลง', painChangeText(7, 3), 'ปวดน้อยลง 57%');
check('% ปวดเท่าเดิม', painChangeText(5, 5), 'ระดับปวดเท่าเดิม');
check('% จาก 0', painChangeText(0, 3), 'ปวดเพิ่มขึ้น 3 คะแนน');

console.log(fail ? `\n${fail} ข้อไม่ผ่าน` : `ผ่านทั้งหมด ${cases.length + 9} ข้อ`);
process.exit(fail ? 1 : 0);
