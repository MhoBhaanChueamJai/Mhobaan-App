import type { IconName } from '../design-system';
/**
 * หัวข้อคลังความรู้ในแอป (หน้า "คลังความรู้")
 * ------------------------------------------------------------------
 * 1) ระบบหมอบ้านเชื่อมใจ — Spec ของทีม (docs/MOHBAN_SPEC.md · 1 หัวข้อ = 1 หน้าในคลัง)
 * 2) Knowledge Hub หมอพื้นบ้าน — 8 เล่มใน `knowledge hub mohbanhealth/E-book/` (สร้างคลังด้วย scripts/build-kb.py)
 * f ต้องตรงกับชื่อเอกสารใน assets/kb/kb.txt (TITLE ใน build-kb.py) — ใช้ค้นเฉพาะเล่มและแสดงอ้างอิง
 */

export interface KnowledgeBook {
  /** ชื่อเอกสารใน kb.txt */
  f: string;
  /** ผู้จัดทำ · ปี */
  by: string;
  /** เล่มนี้ตอบเรื่องอะไร (1 ประโยค) */
  about: string;
  icon: IconName;
  /** คำค้นแนะนำ (แตะแล้วค้นในเล่ม) */
  ask: string[];
  /** หน่วยของ p (ค่าเริ่มต้น "หน้า") */
  unit?: string;
  /** สารบัญ: แตะเพื่ออ่านทั้งหัวข้อ (เอกสารสั้นที่อ่านไล่ได้) */
  toc?: { p: number; title: string }[];
}

export interface KnowledgeTopic {
  id: string;
  title: string;
  sub: string;
  books: KnowledgeBook[];
  /** ยังไม่มีเนื้อหา → แสดงป้าย "รอข้อมูล" */
  pending?: boolean;
}

